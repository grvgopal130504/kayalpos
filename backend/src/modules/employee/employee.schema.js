import { z } from 'zod';

// Same phone format check as Supplier's createSupplierSchema (see
// backend/src/modules/supplier/supplier.schema.js) — duplicated rather than
// shared since the two masters' schemas are otherwise unrelated, same
// pattern already used across this codebase (e.g. Selling Price/Price List
// each keep their own date-range superRefine rather than importing one
// shared helper).
function withFormatChecks(schema) {
  return schema.superRefine((data, ctx) => {
    if (data.phone) {
      const digits = data.phone.replace(/\D/g, '');
      if (digits.length !== 10) {
        ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['phone'], message: 'Enter a valid 10-digit phone number' });
      }
    }
    if (data.loginUsername && !/^[a-zA-Z][a-zA-Z0-9_.]{2,29}$/.test(data.loginUsername)) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: ['loginUsername'],
        message: 'Login user must start with a letter and be 3-30 characters (letters, numbers, "_", ".")',
      });
    }
  });
}

// `code` is auto-generated by the CRUD factory (EMP001, EMP002, ...) unless
// the client supplies one explicitly — same convention as every other
// master (see crudFactory.js's nextCode()). `outletId` is required here even
// though the database column is nullable (see the model's own doc comment
// in schema.prisma for why — same "nullable for delete safety, required by
// business rule" pattern as BatchSerial.warehouseId). `loginUsername` is
// deliberately NOT validated for uniqueness or checked against the real
// `User` table — it's a descriptive field, not a live login credential (see
// the Employee model's own doc comment).
const employeeBaseSchema = z.object({
  code: z.string().trim().min(1).optional(),
  name: z.string().trim().min(1, 'Employee name is required').max(150, 'Name cannot exceed 150 characters'),
  type: z.string().trim().min(1, 'Select an employee type'),
  outletId: z.string().trim().min(1, 'Select a location'),
  phone: z.string().trim().optional().nullable(),
  email: z.string().trim().email('Enter a valid email').optional().or(z.literal('')).nullable(),
  loginUsername: z.string().trim().optional().nullable(),
  joiningDate: z.coerce.date({ invalid_type_error: 'Enter a valid joining date' }).optional().nullable(),
  status: z.enum(['ACTIVE', 'INACTIVE']).default('ACTIVE'),
});

export const createEmployeeSchema = withFormatChecks(employeeBaseSchema);
export const updateEmployeeSchema = withFormatChecks(employeeBaseSchema.partial());
