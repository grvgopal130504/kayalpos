import { z } from 'zod';

// One line-item row from the Create Stock Transfer form's item grid. Every
// filled row (itemCode non-blank) is part of the document — same "every
// filled row counts" convention Stock Indent uses. availableQty/unitCost/
// totalCost are NOT accepted from the client — those are always recomputed
// server-side from the real Product master (see stockTransfer.service.js's
// computeItems), so a client can never fabricate its own numbers for them.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  transferQty: z.coerce.number().positive('Transfer qty must be greater than 0'),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (TRF-00001, TRF-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `fromOutletId`/`toOutletId` are validated against real Outlet
// rows for this tenant in the service layer (not here — Zod only checks
// shape, not database existence); `indentRef`, when provided, is likewise
// validated there against a real, approved StockIndent for this tenant.
// `status` only ever accepts 'draft' or 'in-transit' here — 'received'/
// 'cancelled' are not settable through this endpoint (there's no real
// receive/cancel workflow wired up yet), same rule Stock Indent applies to
// its own not-yet-reachable statuses.
export const createStockTransferSchema = z.object({
  code: z.string().trim().min(1).optional(),
  transferDate: z.coerce.date(),
  indentRef: z.string().trim().optional().or(z.literal('')),
  fromOutletId: z.string().trim().min(1, 'From Outlet is required'),
  toOutletId: z.string().trim().min(1, 'To Outlet is required'),
  department: z.string().trim().optional().or(z.literal('')),
  purpose: z.string().trim().optional().or(z.literal('')),
  priority: z.enum(['low', 'medium', 'high', 'urgent']).default('medium'),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  costCenter: z.string().trim().optional().or(z.literal('')),
  remarks: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'in-transit']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
});

// Edit mode always resubmits the whole form (see CreateStockTransferPage),
// so the update schema keeps the same full validation instead of
// `.partial()` — same convention as Stock Indent/Sales Order/Sales Invoice.
// A genuinely 'received'/'cancelled' transfer can't be edited back into
// draft/in-transit through this form either (those statuses aren't offered
// here in the first place) — moot today since nothing sets them yet.
export const updateStockTransferSchema = createStockTransferSchema;
