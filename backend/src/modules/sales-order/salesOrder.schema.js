import { z } from 'zod';

// One line-item row as sent by the Create Sales Order form's item grid.
// Coerced to numbers here (never trusted as-is) so a stray "10abc" or a
// negative value can never reach the database — the frontend's own zod
// schema blocks these at the form too, but the backend is the actual source
// of truth, same rule as every other module's schema.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  qty: z.coerce.number().positive('Qty must be greater than 0'),
  unit: z.string().trim().optional().or(z.literal('')),
  unitPrice: z.coerce.number().nonnegative('Unit price cannot be negative'),
  discountPercent: z.coerce.number().min(0, 'Discount cannot be negative').max(100, 'Discount cannot exceed 100%').default(0),
  taxCode: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (SO-00001, SO-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `status` only ever accepts 'pending' or 'confirmed' here —
// 'delivered' is not settable through this endpoint (there's no Sales
// Invoice conversion step wired up yet to actually deliver an order), same
// rule Sales Quotation applies to its own 'converted' status.
export const createSalesOrderSchema = z
  .object({
    code: z.string().trim().min(1).optional(),
    customerId: z.string().trim().min(1, 'Select a customer'),
    contactPerson: z.string().trim().optional().or(z.literal('')),
    mobile: z.string().trim().optional().or(z.literal('')),
    email: z.string().trim().email('Enter a valid email address').optional().or(z.literal('')),
    address: z.string().trim().optional().or(z.literal('')),
    orderDate: z.coerce.date({ errorMap: () => ({ message: 'Order date is required' }) }),
    deliveryDate: z.coerce.date({ errorMap: () => ({ message: 'Delivery date is required' }) }),
    paymentTerms: z.string().trim().optional().or(z.literal('')),
    salesPerson: z.string().trim().min(1, 'Select a sales person'),
    currency: z.string().trim().min(1).default('INR'),
    quotationRef: z.string().trim().optional().or(z.literal('')),
    referenceDate: z.coerce.date().optional().nullable(),
    priceList: z.string().trim().optional().or(z.literal('')),
    remarks: z.string().trim().optional().or(z.literal('')),
    notes: z.string().trim().optional().or(z.literal('')),
    extraDiscount: z.coerce.number().nonnegative('Discount cannot be negative').default(0),
    status: z.enum(['pending', 'confirmed']).default('pending'),
    items: z.array(itemRowSchema).min(1, 'Add at least one item'),
  })
  .superRefine((values, ctx) => {
    if (values.deliveryDate < values.orderDate) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['deliveryDate'], message: 'Delivery date cannot be before the order date' });
    }
    if (values.referenceDate && values.referenceDate > values.orderDate) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['referenceDate'], message: 'Reference date cannot be after the order date' });
    }
  });

// Edit mode always resubmits the whole form (see CreateSalesOrderPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Sales Quotation/Promotion/GiftVoucher/LoyaltyProgram.
// A genuinely 'delivered' order can't be edited back into pending/confirmed
// through this form either (that status isn't offered here in the first
// place, same limitation Sales Quotation accepts for 'converted') — moot
// today since nothing sets 'delivered' yet.
export const updateSalesOrderSchema = createSalesOrderSchema;
