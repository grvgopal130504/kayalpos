import { z } from 'zod';

// One selected line-item row as sent by the Create Barcode & Label form's
// item grid — only rows the user checked are ever included here (the
// frontend filters to `selected: true` before submitting, mirroring
// LabelPrintSummaryCard's own selected-only totals). Coerced/trimmed here
// (never trusted as-is) so a stray blank or negative print qty can never
// reach the database, same rule every other module's backend schema follows.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  barcode: z.string().trim().optional().or(z.literal('')),
  printQty: z.coerce.number().positive('Print qty must be greater than 0'),
  fromSerialBatch: z.string().trim().optional().or(z.literal('')),
  toSerialBatch: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (LBL-00001, LBL-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `status` only ever accepts 'draft' or 'pending-print' here —
// 'printed' is not settable through this endpoint (there's no real label
// printing step wired up yet), same rule Sales Order/Sales Invoice apply to
// their own not-yet-reachable statuses.
export const createBarcodeLabelSchema = z.object({
  code: z.string().trim().min(1).optional(),
  labelName: z.string().trim().min(1, 'Label name is required'),
  labelType: z.enum(['barcode', 'qr-code', 'price-tag']).default('barcode'),
  labelSize: z.string().trim().min(1, 'Select a label size'),
  printTemplate: z.string().trim().optional().or(z.literal('')),
  labelsAcross: z.coerce.number().int().positive().optional().nullable(),
  labelsDown: z.coerce.number().int().positive().optional().nullable(),
  remarks: z.string().trim().optional().or(z.literal('')),
  itemCategory: z.string().trim().optional().or(z.literal('')),
  item: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  brand: z.string().trim().optional().or(z.literal('')),
  warehouse: z.string().trim().optional().or(z.literal('')),
  batchNo: z.string().trim().optional().or(z.literal('')),
  fromItemCode: z.string().trim().optional().or(z.literal('')),
  toItemCode: z.string().trim().optional().or(z.literal('')),
  barcodeType: z.string().trim().min(1, 'Select a barcode type'),
  additionalFilter: z.string().trim().optional().or(z.literal('')),
  sortBy: z.string().trim().min(1, 'Select a sort order'),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'pending-print']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Select at least one item to print'),
});

// Edit mode always resubmits the whole form (see CreateBarcodeLabelPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Sales Order/Sales Invoice. A genuinely 'printed'
// batch can't be edited back into draft/pending-print through this form
// either (that status isn't offered here in the first place) — moot today
// since nothing sets 'printed' yet.
export const updateBarcodeLabelSchema = createBarcodeLabelSchema;
