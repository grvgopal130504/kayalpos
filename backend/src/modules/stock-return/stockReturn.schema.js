import { z } from 'zod';

// One line-item row from the Create Stock Return form's item grid. Every
// filled row (itemCode non-blank) is part of the document — same "every
// filled row counts" convention Stock Receipt/Stock Indent/Stock Transfer
// use. unitCost/discount/tax are accepted as-is from the client — they're
// the real figures the user typed for the returned goods, not values
// fabricated from a Product master lookup. Only `totalCost` is never
// accepted from the client — that's always recomputed server-side (see
// stockReturn.service.js's computeItems).
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  returnedQty: z.coerce.number().positive('Returned qty must be greater than 0'),
  unitCost: z.coerce.number().min(0, 'Unit cost cannot be negative').default(0),
  discount: z.coerce.number().min(0, 'Discount cannot be negative').max(100, 'Discount cannot exceed 100%').default(0),
  tax: z.coerce.number().min(0, 'Tax cannot be negative').max(100, 'Tax cannot exceed 100%').default(0),
  warehouse: z.string().trim().optional().or(z.literal('')),
  batchNo: z.string().trim().optional().or(z.literal('')),
  expiryDate: z.coerce.date().optional().nullable(),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (RRT-00001, RRT-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `supplierId`/`fromOutletId` are validated against real Supplier/
// Outlet rows for this tenant in the service layer (not here — Zod only
// checks shape, not database existence). `referenceType`/`referenceNo` are
// free text — there is no Purchase Invoice/GRN master table to validate
// against. `status` only ever accepts 'draft' or 'accepted', matching the
// reference design's own two-state Draft/Accepted return lifecycle.
export const createStockReturnSchema = z.object({
  code: z.string().trim().min(1).optional(),
  returnDate: z.coerce.date(),
  returnType: z.string().trim().min(1, 'Return type is required'),
  referenceType: z.string().trim().min(1, 'Reference type is required'),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  referenceDate: z.coerce.date().optional().nullable(),
  returnReason: z.string().trim().optional().or(z.literal('')),
  returnRemarks: z.string().trim().optional().or(z.literal('')),
  supplierId: z.string().trim().min(1, 'Supplier is required'),
  fromOutletId: z.string().trim().min(1, 'From Outlet / HO is required'),
  costCenter: z.string().trim().optional().or(z.literal('')),
  contactPerson: z.string().trim().optional().or(z.literal('')),
  mobileNo: z.string().trim().optional().or(z.literal('')),
  grnDcNo: z.string().trim().optional().or(z.literal('')),
  grnDcDate: z.coerce.date().optional().nullable(),
  vehicleNo: z.string().trim().optional().or(z.literal('')),
  transporter: z.string().trim().optional().or(z.literal('')),
  otherRemarks: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'accepted']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
});

// Edit mode always resubmits the whole form (see CreateStockReturnPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Stock Receipt/Stock Indent/Stock Transfer.
export const updateStockReturnSchema = createStockReturnSchema;
