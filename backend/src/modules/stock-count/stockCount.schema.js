import { z } from 'zod';

// One line-item row from the Create Stock Count form's item grid. Every
// filled row (itemCode non-blank) is part of the document — same "every
// filled row counts" convention Stock Wastage/Stock Return use.
// systemQty/countedQty/unitCost are accepted as-is from the client — the
// real figures the user typed off the physical count, not values fabricated
// from a Product master lookup. Only `varianceQty`/`varianceValue` are
// never accepted from the client — those are always recomputed server-side
// (see stockCount.service.js's computeItems). There is no discount/tax
// field here — a stock count reconciliation has no such concept.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  systemQty: z.coerce.number().min(0, 'System qty cannot be negative').default(0),
  countedQty: z.coerce.number().min(0, 'Counted qty cannot be negative'),
  unitCost: z.coerce.number().min(0, 'Unit cost cannot be negative').default(0),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (CNT-00001, CNT-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `preparedBy`/`approvedBy` are plain free text the user typed —
// never auto-stamped from the logged-in actor. `status` only ever accepts
// 'draft' or 'completed', matching the reference design's own two-state
// Draft/Completed count lifecycle.
export const createStockCountSchema = z.object({
  code: z.string().trim().min(1).optional(),
  countDate: z.coerce.date(),
  warehouse: z.string().trim().min(1, 'Warehouse is required'),
  department: z.string().trim().optional().or(z.literal('')),
  costCenter: z.string().trim().optional().or(z.literal('')),
  countReason: z.string().trim().min(1, 'Count reason is required'),
  countRemarks: z.string().trim().optional().or(z.literal('')),
  countType: z.string().trim().min(1, 'Count type is required'),
  countBy: z.string().trim().min(1, 'Count by is required'),
  binRack: z.string().trim().optional().or(z.literal('')),
  startCountTime: z.string().trim().optional().or(z.literal('')),
  endCountTime: z.string().trim().optional().or(z.literal('')),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  preparedBy: z.string().trim().optional().or(z.literal('')),
  approvedBy: z.string().trim().optional().or(z.literal('')),
  otherNotes: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'completed']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
});

// Edit mode always resubmits the whole form (see CreateStockCountPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Stock Wastage/Stock Return/Stock Receipt.
export const updateStockCountSchema = createStockCountSchema;
