import { z } from 'zod';

// One line-item row from the Create Stock Wastage form's item grid. Every
// filled row (itemCode non-blank) is part of the document — same "every
// filled row counts" convention Stock Return/Stock Receipt use.
// availableQty/wastageQty/unitCost are accepted as-is from the client — the
// real figures the user typed off the shelf/stock check, not values
// fabricated from a Product master lookup. Only `totalValue` is never
// accepted from the client — that's always recomputed server-side (see
// stockWastage.service.js's computeItems). There is no discount/tax field
// here — a stock write-off has no such concept, unlike Stock Return/Stock
// Receipt's priced lines.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  batchNo: z.string().trim().optional().or(z.literal('')),
  expiryDate: z.coerce.date().optional().nullable(),
  availableQty: z.coerce.number().min(0, 'Available qty cannot be negative').default(0),
  wastageQty: z.coerce.number().positive('Wastage qty must be greater than 0'),
  unitCost: z.coerce.number().min(0, 'Unit cost cannot be negative').default(0),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (WST-00001, WST-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `outletId` is validated against a real Outlet row for this tenant
// in the service layer (not here — Zod only checks shape, not database
// existence). `preparedBy`/`approvedBy` are plain free text the user typed —
// never auto-stamped from the logged-in actor. `status` only ever accepts
// 'draft' or 'approved', matching the reference design's own two-state
// Draft/Approved wastage lifecycle.
export const createStockWastageSchema = z.object({
  code: z.string().trim().min(1).optional(),
  wastageDate: z.coerce.date(),
  wastageType: z.string().trim().min(1, 'Wastage type is required'),
  department: z.string().trim().optional().or(z.literal('')),
  costCenter: z.string().trim().optional().or(z.literal('')),
  wastageReason: z.string().trim().optional().or(z.literal('')),
  wastageRemarks: z.string().trim().optional().or(z.literal('')),
  outletId: z.string().trim().min(1, 'Outlet / Location is required'),
  warehouse: z.string().trim().optional().or(z.literal('')),
  binRack: z.string().trim().optional().or(z.literal('')),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  preparedBy: z.string().trim().optional().or(z.literal('')),
  approvedBy: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'approved']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
});

// Edit mode always resubmits the whole form (see CreateStockWastagePage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Stock Receipt/Stock Return.
export const updateStockWastageSchema = createStockWastageSchema;
