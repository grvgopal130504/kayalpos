import { z } from 'zod';

// One line-item row from the Create Stock Indent form's item grid. Every
// filled row (itemCode non-blank) is part of the document — unlike Barcode
// & Label's selected-only rows, there's no per-row checkbox here, same
// "every filled row counts" convention Sales Quotation/Order/Invoice use.
// availableQty/unitValue/amount are NOT accepted from the client — those are
// always recomputed server-side from the real Product master (see
// stockIndent.service.js's computeItems), so a client can never fabricate
// its own numbers for them.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  requiredQty: z.coerce.number().positive('Required qty must be greater than 0'),
  issueWarehouse: z.string().trim().optional().or(z.literal('')),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (IND-00001, IND-00002, ...) unless
// the client supplies one explicitly — same convention as every other
// module. `fromOutletId`/`toOutletId`/`locationId` are validated against
// real Outlet rows for this tenant in the service layer (not here — Zod
// only checks shape, not database existence). `requestor` is a required
// plain free-text field — there is no Employee/Requestor master, so this is
// never a fixed dropdown of fabricated names. `status` only ever accepts
// 'draft' or 'pending-approval' here — 'approved'/'rejected' are not
// settable through this endpoint (there's no real approval-workflow step
// wired up yet), same rule Sales Order/Sales Invoice/Barcode & Label apply
// to their own not-yet-reachable statuses.
export const createStockIndentSchema = z.object({
  code: z.string().trim().min(1).optional(),
  indentDate: z.coerce.date(),
  requiredDate: z.coerce.date(),
  department: z.string().trim().min(1, 'Department is required'),
  purpose: z.string().trim().optional().or(z.literal('')),
  fromOutletId: z.string().trim().min(1, 'From Outlet is required'),
  toOutletId: z.string().trim().min(1, 'To Outlet is required'),
  requestor: z.string().trim().min(1, 'Requestor is required'),
  priority: z.enum(['low', 'medium', 'high', 'urgent']).default('medium'),
  designation: z.string().trim().optional().or(z.literal('')),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  locationId: z.string().trim().optional().or(z.literal('')),
  costCenter: z.string().trim().optional().or(z.literal('')),
  remarks: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'pending-approval']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
}).superRefine((data, ctx) => {
  if (data.requiredDate < data.indentDate) {
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      path: ['requiredDate'],
      message: 'Required date cannot be before the indent date',
    });
  }
});

// Edit mode always resubmits the whole form (see CreateStockIndentPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Sales Order/Sales Invoice/Barcode & Label. A
// genuinely 'approved'/'rejected' indent can't be edited back into
// draft/pending-approval through this form either (those statuses aren't
// offered here in the first place) — moot today since nothing sets them yet.
export const updateStockIndentSchema = createStockIndentSchema;
